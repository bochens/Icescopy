CONFIG={'learning_rate':5e-5,'weight_decay':1e-4,'epochs':4,'steps_per_epoch':40,
        'batch_triplets':32,'margin':.2,'teacher_preservation':.1,'gradient_clip':5.,
        'threads':4,'seed':61003,'manual_variants':8,'maximum_crops':20000,
        'initialization':'preserved_synthetic_posttrained_parent',
        'sampling':'Half manual/half synthetic replay; equal instruments; cycle distinct positive object IDs.',
        'selection':'Best separate synthetic validation among trained checkpoints after all manual positives receive updates.',
        'threshold_objective':'Predeclared F2 on separate synthetic calibration; misses cost four times extras.'}


def verify_parent_prefix(parent,cache):
    crops=np.load(cache/'crops.npy',mmap_mode='r');saved=np.load(cache/'prefix.npy',mmap_mode='r')
    ids=np.linspace(0,len(crops)-1,8).astype(int);prefix,_=trainable_suffix(parent)
    with parent.torch.no_grad():actual=prefix(parent.input_tensor(np.asarray(crops[ids],np.float32)/255)).cpu().numpy()
    difference=float(np.max(np.abs(actual-saved[ids])))
    if not np.isfinite(difference) or difference>1e-5:raise ValueError('Synthetic replay prefix is incompatible with the parent/preprocessing.')
    return {'compatible':True,'max_abs_difference':difference,'absolute_tolerance':1e-5,'crop_indices':ids.tolist()}


def combine_parent_cache(parent,folder,synthetic_cache,synthetic_rows,real_folder,real_rows):
    """Never copy the original teacher: replay targets are regenerated by parent."""
    old=np.load(synthetic_cache/'prefix.npy',mmap_mode='r');real=np.load(real_folder/'prefix.npy',mmap_mode='r')
    if len(old)!=len(synthetic_rows) or len(real)!=len(real_rows) or old.shape[1:]!=real.shape[1:]:
        raise ValueError('Replay/manual prefix arrays do not match records.')
    prefix=np.lib.format.open_memmap(folder/'prefix.npy',mode='w+',dtype=np.float32,shape=(len(old)+len(real),*old.shape[1:]))
    prefix[:len(old)]=old;prefix[len(old):]=real;prefix.flush()
    teacher=np.lib.format.open_memmap(folder/'teacher.npy',mode='w+',dtype=np.float32,shape=(len(prefix),576))
    _,suffix=trainable_suffix(parent);start=time.perf_counter()
    with parent.torch.no_grad():
        for first in range(0,len(old),64):
            last=min(first+64,len(old))
            values=parent.torch.from_numpy(np.asarray(prefix[first:last]).copy())
            teacher[first:last]=suffix_embeddings(suffix,values).cpu().numpy()
        teacher[len(old):]=np.load(real_folder/'teacher.npy',mmap_mode='r')
    teacher.flush();del prefix,teacher
    records=copy.deepcopy(synthetic_rows)
    for row in real_rows:records.append(dict(row,index=len(records)))
    (folder/'crop-index.json').write_text(json.dumps(records)+'\n')
    return records,{'parent_teacher_regenerated':True,'original_teacher_used_for_targets':False,
                    'replay_teacher_seconds':time.perf_counter()-start,
                    'prefix_sha256':sha256(folder/'prefix.npy'),'teacher_sha256':sha256(folder/'teacher.npy')}


def train_water(parent,records,folder,source,config=None,sampler_class=WaterTriplets,final_pass_only=False):
    cfg=dict(CONFIG if config is None else config);t=parent.torch
    t.manual_seed(cfg['seed']);rng=np.random.default_rng(cfg['seed']);_,suffix=trainable_suffix(parent)
    before={n:v.detach().cpu().clone() for n,v in parent.model.features.state_dict().items()}
    frozen=tensor_hash(prefix_state(parent.model.features));bn=tensor_hash(batchnorm_buffers(parent.model.features))
    prefix=np.load(folder/'prefix.npy',mmap_mode='r');teacher=np.load(folder/'teacher.npy',mmap_mode='r')
    fit=sampler_class(records,'fit');validation=sampler_class(records,'validation')
    fixed=validation.sample(np.random.default_rng(cfg['seed']+1),640);np.save(folder/'validation-triplets.npy',fixed)
    optimizer=t.optim.AdamW(suffix.parameters(),lr=cfg['learning_rate'],weight_decay=cfg['weight_decay'])
    def val_loss():
        losses=[]
        with t.no_grad():
            for first in range(0,len(fixed),cfg['batch_triplets']):
                values,target,local=batch_embeddings(suffix,prefix,teacher,fixed[first:first+cfg['batch_triplets']])
                loss,_,_=adaptation_loss(values,target,local,cfg['margin'],cfg['teacher_preservation']);losses.append(float(loss))
        return float(np.mean(losses))
    initial=val_loss();history=[];best_loss=float('inf');best_state=None;best_epoch=None;start=time.perf_counter()
    print('Parent initial synthetic validation',round(initial,6),flush=True)
    for epoch in range(1,cfg['epochs']+1):
        epoch_start=time.perf_counter();losses=[]
        for step in range(cfg['steps_per_epoch']):
            sampled=fit.sample(rng,cfg['batch_triplets']);optimizer.zero_grad(set_to_none=True)
            values,target,local=batch_embeddings(suffix,prefix,teacher,sampled)
            loss,ranking,preserve=adaptation_loss(values,target,local,cfg['margin'],cfg['teacher_preservation'])
            loss.backward();t.nn.utils.clip_grad_norm_(suffix.parameters(),cfg['gradient_clip']);optimizer.step()
            fit.mark_updated(sampled);losses.append([float(loss.detach()),float(ranking.detach()),float(preserve.detach())])
            if (step+1)%20==0:print('Water pass',epoch,'step',step+1,'/',cfg['steps_per_epoch'],flush=True)
        val=val_loss();eligible=fit.all_manual_updated()
        row={'epoch':epoch,'train_loss':float(np.mean(np.asarray(losses)[:,0])),
             'ranking_loss':float(np.mean(np.asarray(losses)[:,1])),'preservation_loss':float(np.mean(np.asarray(losses)[:,2])),
             'validation_loss':val,'seconds':time.perf_counter()-epoch_start,
             'checkpoint_eligible':eligible,'positive_update_coverage':fit.object_coverage()}
        if hasattr(fit,'negative_coverage'):row['center_negative_update_coverage']=fit.negative_coverage()
        history.append(row);print('Water pass complete',json.dumps(row),flush=True)
        if eligible and val<best_loss and (not final_pass_only or epoch==cfg['epochs']):
            best_loss=val;best_epoch=epoch;best_state={n:v.detach().cpu().clone() for n,v in parent.model.features.state_dict().items()}
        (folder/'history.json').write_text(json.dumps(history,indent=2)+'\n')
    if best_state is None:raise RuntimeError('No trained checkpoint updated all manual positives within the fixed budget.')
    parent.model.features.load_state_dict(best_state);changes=changed_tensors(before,parent.model.features.state_dict())
    metadata={'config':cfg,'best_epoch':best_epoch,'initial_validation_loss':initial,'best_validation_loss':best_loss,
              'validation_improved_over_parent':best_loss<initial,'history':history,'training_seconds':time.perf_counter()-start,
              'frozen_prefix_sha256':frozen,'batchnorm_buffers_sha256':bn,
              'frozen_prefix_unchanged':tensor_hash(prefix_state(parent.model.features))==frozen,
              'batchnorm_buffers_unchanged':tensor_hash(batchnorm_buffers(parent.model.features))==bn,
              'changed_tensor_l2_norms':changes,'changed_convolution_tensors':{n:v for n,v in changes.items() if before[n].ndim==4},
              'selected_positive_update_coverage':history[best_epoch-1]['positive_update_coverage'],
              'source':source,'note':'Starts from the preserved parent encoder. Manual native-radius objects and synthetic replay update weights. Real-frame recovery is training diagnostics. '+
              ('Uses the fixed final pass after complete update coverage; separate synthetic validation is reported, and synthetic calibration chooses thresholds.' if final_pass_only else
               'Separate synthetic validation chooses weights, and synthetic calibration chooses thresholds.')}
    if hasattr(fit,'negative_coverage'):
        metadata['selected_center_negative_update_coverage']=history[best_epoch-1]['center_negative_update_coverage']
    if final_pass_only:
        metadata.update(checkpoint_selection='Fixed final training pass after complete positive/invalid-center update coverage.',
                        selected_validation_loss=best_loss,
                        minimum_validation_loss_across_all_passes=min(r['validation_loss'] for r in history))
    if not metadata['changed_convolution_tensors'] or not metadata['frozen_prefix_unchanged'] or not metadata['batchnorm_buffers_unchanged']:
        raise RuntimeError('Water adaptation violated the actual-update/frozen-layer contract.')
    save_checkpoint(folder/'encoder.pt',parent,metadata)
    (folder/'training-report.json').write_text(json.dumps(metadata,indent=2)+'\n')
    return metadata


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    for name in ('manual-labels','synthetic-labels','synthetic-cache','parent-checkpoint','output'):
        parser.add_argument('--'+name,type=Path,required=True)
    args=parser.parse_args();manifest=json.loads(args.manual_labels.read_text());scenes=check_manual_manifest(manifest)
    parent_sha=sha256(args.parent_checkpoint)
    if manifest['starting_encoder']['sha256']!=parent_sha:raise ValueError('Manual manifest specifies a different parent encoder.')
    old,old_source=load_synthetic_records(args.synthetic_labels,args.synthetic_cache)
    count=len(old)+sum(len(s['targets'])+len(s['negatives']) for s in scenes)*CONFIG['manual_variants']
    if count>CONFIG['maximum_crops']:raise ValueError('Planned manual/replay crop bank exceeds the declared20k limit.')
    parent=FineTunedEncoder(args.parent_checkpoint,CONFIG['threads']);compatibility=verify_parent_prefix(parent,args.synthetic_cache)
    args.output.mkdir(parents=True,exist_ok=False);cv2.setNumThreads(CONFIG['threads'])
    (args.output/'config.json').write_text(json.dumps(CONFIG,indent=2)+'\n')
    real_folder=args.output/'manual-crops';real_folder.mkdir()
    real=build_manual_crops(scenes,real_folder,CONFIG['manual_variants'],CONFIG['seed'])
    real_cache=cache_prefix(parent,real_folder,real)
    records,combined=combine_parent_cache(parent,args.output,args.synthetic_cache,old,real_folder,real)
    source={'manual_manifest_sha256':sha256(args.manual_labels),'synthetic_manifest_sha256':sha256(args.synthetic_labels),
            'parent_encoder_sha256':parent_sha,'parent_encoder_path':str(args.parent_checkpoint.resolve()),
            'manual_scene_hashes':{s['id']:s['sha256'] for s in scenes},
            'synthetic_cache_source':old_source,'synthetic_prefix_compatibility':compatibility,
            'manual_cache':real_cache,'combined_cache':combined,
            'manual_positives':sum(len(s['targets']) for s in scenes),'manual_negatives':sum(len(s['negatives']) for s in scenes),
            'manual_crops':len(real),'combined_crops':len(records),'real_heldout_images':0}
    print('Water bank',len(records),'crops;',source['manual_positives'],'manual positives',flush=True)
    train_water(parent,records,args.output,source)
    if sha256(args.parent_checkpoint)!=parent_sha:raise RuntimeError('Preserved parent checkpoint changed during adaptation.')


if __name__=='__main__':main()
